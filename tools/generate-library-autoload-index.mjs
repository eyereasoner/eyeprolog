#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseClauses } from '../src/parser.js';
import { ATOM, COMPOUND, NUMBER, Env, properListItems } from '../src/term.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const libDir = path.join(root, 'src', 'lib');
const outputFile = path.join(root, 'src', 'library-autoload-index.js');

function predicateIndicator(nameTerm, arityTerm, extraArity = 0) {
  if (nameTerm?.type !== ATOM || arityTerm?.type !== NUMBER || !/^\d+$/.test(arityTerm.name)) return null;
  const arity = Number(arityTerm.name) + extraArity;
  return { name: nameTerm.name, arity, key: `${nameTerm.name}/${arity}` };
}

function moduleExports(term) {
  const items = properListItems(term, new Env());
  if (items == null) throw new Error('module export list is not a proper list');
  const exports = [];
  for (const item of items) {
    if (item?.type === COMPOUND && item.name === 'op' && item.arity === 3) continue;
    if (item?.type !== COMPOUND || !['/', '//'].includes(item.name) || item.arity !== 2) {
      throw new Error(`unsupported module export: ${item?.name ?? '<unknown>'}`);
    }
    const indicator = predicateIndicator(item.args[0], item.args[1], item.name === '//' ? 2 : 0);
    if (indicator == null) throw new Error('invalid predicate indicator in module export');
    exports.push(indicator);
  }
  return exports;
}

function localDefinitionKey(clause) {
  const head = clause?.head;
  if (head == null) return null;
  if (head.type === COMPOUND && head.name === ':-' && head.arity === 1) return null;
  if (head.type === COMPOUND && head.name === '-->' && head.arity === 2) {
    const nt = head.args[0];
    if (nt?.type !== ATOM && nt?.type !== COMPOUND) return null;
    return `${nt.name}/${nt.arity + 2}`;
  }
  if (head.type !== ATOM && head.type !== COMPOUND) return null;
  return `${head.name}/${head.arity}`;
}

const candidates = new Map();
const modules = [];
for (const filename of fs.readdirSync(libDir).filter((name) => name.endsWith('.pl')).sort()) {
  const source = fs.readFileSync(path.join(libDir, filename), 'utf8');
  const clauses = parseClauses(source, { filename: `src/lib/${filename}`, sourceMetadata: false });
  const definitions = new Set(clauses.map(localDefinitionKey).filter(Boolean));
  let moduleName = null;
  let exports = null;
  for (const clause of clauses) {
    const directive = clause?.head?.type === COMPOUND && clause.head.name === ':-' && clause.head.arity === 1
      ? clause.head.args[0]
      : null;
    if (directive?.type !== COMPOUND || directive.name !== 'module' || directive.arity !== 2) continue;
    if (directive.args[0]?.type !== ATOM) throw new Error(`${filename}: invalid module name`);
    moduleName = directive.args[0].name;
    exports = moduleExports(directive.args[1]);
    break;
  }
  if (moduleName == null || exports == null) throw new Error(`${filename}: missing module/2 declaration`);
  modules.push(moduleName);
  for (const indicator of exports) {
    const list = candidates.get(indicator.key) ?? [];
    list.push({ library: moduleName, local: definitions.has(indicator.key) });
    candidates.set(indicator.key, list);
  }
}

const providers = {};
const ambiguous = {};
for (const [key, list] of [...candidates.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  if (list.length === 1) {
    providers[key] = list[0].library;
    continue;
  }
  const local = list.filter((entry) => entry.local);
  if (local.length === 1) {
    providers[key] = local[0].library;
    continue;
  }
  ambiguous[key] = list.map((entry) => entry.library).sort();
}

const renderObject = (value) => JSON.stringify(value, null, 2)
  .replace(/^\{/m, 'Object.freeze({')
  .replace(/\}$/m, '})');
const text = `// Generated by tools/generate-library-autoload-index.mjs.\n` +
  `// Do not edit by hand; module/2 export lists under src/lib/ are the source of truth.\n\n` +
  `export const eyePrologLibraryAutoload = ${renderObject(providers)};\n\n` +
  `export const eyePrologAmbiguousLibraryAutoload = ${renderObject(ambiguous)};\n\n` +
  `export const eyePrologLibraryAutoloadModules = Object.freeze(${JSON.stringify(modules.sort(), null, 2)});\n`;
if (process.argv.includes('--check')) {
  const current = fs.existsSync(outputFile) ? fs.readFileSync(outputFile, 'utf8') : '';
  if (current !== text) {
    console.error(`${path.relative(root, outputFile)} is stale; run npm run generate`);
    process.exit(1);
  }
  console.log(`${path.relative(root, outputFile)} is up to date`);
} else {
  fs.writeFileSync(outputFile, text);
  console.log(`wrote ${path.relative(root, outputFile)} (${Object.keys(providers).length} predicates, ${Object.keys(ambiguous).length} ambiguous)`);
}
